"""Assemble the explainer page ("a clustering lens") from the template plus recorded runs
(record_pipeline_run.py).  Two roles: HERO (scrubber and step-through) and LEVELS (choosing a level).

  default               CIFAR-100 / CLIP in both roles -> build/how-dyf-works-cifar100-clip.html (standalone, run inlined)
  --hero A --levels B   two datasets, e.g. mnist_pca50 + clinc150_minilm -> build/how-dyf-works.html
  --docs                write the homepage of the Quarto site instead (docs/):
                          index.qmd            page-layout custom, no body; pulls in the two includes
                          _lens_header.html    fonts + the page's CSS + Quarto integration CSS
                          _lens_body.html      markup + scripts; the run is fetched, not inlined
                          lens/<run>.json      the recorded run (listed under resources in _quarto.yml)

Env: .venv/bin/python benchmarks/site_explainer_2026_11/build_how_dyf_works_page.py [--docs] [--both RUN | --hero RUN --levels RUN]
Also writes build/how-dyf-works.js, the page script alone, for `node --check`.
"""

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SITE = Path.home() / ".cache/dyf_intent_bench/site"
ap = argparse.ArgumentParser()
ap.add_argument("--hero", default=None)
ap.add_argument("--levels", default=None)
ap.add_argument("--both", default=None)
ap.add_argument("--docs", action="store_true")
a = ap.parse_args()
hero, levels = (a.hero, a.levels) if a.hero and a.levels else ((a.both or "cifar100_clip"),) * 2


def run_json(name):
    s = (SITE / f"{name}_pipeline_run_seed42.json").read_text().replace("</", "<\\/")
    return s.replace('"minilm embeddings', '"MiniLM embeddings').replace(
        '"items":"requests"', '"items":"voice-assistant requests"'
    )


QUARTO_CSS = """
/* ---- inside the Quarto site: theme follows Quarto's toggle (body.quarto-dark), not the OS ---- */
body.quarto-dark { --bg: #19181b; --surface: #222126; --ink: #ecebee; --ink-2: #b9b6bf; --ink-3: #85818c; --rule: #37353d;
  --accent: #f0627a; --accent-2: #f9a826; --pt-idle: #5d5a64; --code-bg: #2a2930;
  --h0: #3987e5; --h1: #d95926; --h2: #199e70; --h3: #c98500; --h4: #d55181; --h5: #008300; --h6: #9085e9; --h7: #e66767; color-scheme: dark; }
body, body.quarto-light, body.quarto-dark { background: var(--bg); color: var(--ink); }
.wrap { padding-top: 12px; }
.wrap h1, .wrap h2, .wrap h3, body.quarto-dark .wrap h1, body.quarto-dark .wrap h2, body.quarto-dark .wrap h3 { color: var(--ink); border: 0; border-image: none; padding-bottom: 0; margin: 0; }
.wrap a { color: inherit; }
.wrap pre, .wrap code { color: var(--ink); }
.wrap figure { display: grid; gap: 12px; margin: 10px 0 0; }
.wrap figcaption { margin-top: 6px; }
.top .logo { display: none; }
.top { border-bottom: 0; padding-block: 10px 0; }
section[id], #top { scroll-margin-top: 72px; }
"""

tpl = (HERE / "how_dyf_works_page_template.html").read_text()
script = re.findall(r"<script>(.*?)</script>", tpl, re.S)
assert len(script) == 1
out = HERE / "build"
out.mkdir(exist_ok=True)
(out / "how-dyf-works.js").write_text(script[0])
slots = ("/*__RUN_DIGITS__*/", "/*__RUN_REQUESTS__*/")
assert all(tpl.count(sl) == 1 for sl in slots)

if not a.docs:
    page = tpl.replace(slots[0], run_json(hero)).replace(slots[1], "null" if levels == hero else run_json(levels))
    tag = hero if hero == levels else f"{hero}-{levels}"
    path = out / (
        "how-dyf-works.html"
        if (hero, levels) == ("mnist_pca50", "clinc150_minilm")
        else f"how-dyf-works-{tag.replace('_', '-')}.html"
    )
    path.write_text(page)
    print(f"wrote {path} ({len(page) / 1e6:.2f} MB): hero {hero}, levels {levels}")
else:
    assert hero == levels, "the docs homepage uses one dataset"
    docs = REPO / "docs"
    (docs / "lens").mkdir(exist_ok=True)
    run_name = f"dyf-lens-{hero.replace('_', '-')}-run-seed42.json"
    (docs / "lens" / run_name).write_text(run_json(hero))
    m = re.search(r"<style>(.*?)</style>", tpl, re.S)
    css = m.group(1)
    # the standalone page follows the OS colour scheme; inside Quarto the site's own toggle decides
    css, k = re.subn(
        r"@media \(prefers-color-scheme: dark\) \{\n  :root:not\(\[data-theme=\"light\"\]\) \{.*?\n  \}\n\}\n",
        "",
        css,
        count=1,
        flags=re.S,
    )
    assert k == 1
    font = re.search(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^>]*>', tpl).group(0)
    (docs / "_lens_header.html").write_text(
        "<!-- generated by benchmarks/site_explainer_2026_11/build_how_dyf_works_page.py --docs; edit the template, not this file -->\n"
        + font
        + "\n<style>"
        + css
        + QUARTO_CSS
        + "</style>\n"
    )
    body = tpl[m.end() :]
    body = body.replace(
        '<script type="application/json" id="run-digits">' + slots[0],
        f'<script type="application/json" id="run-digits" data-src="lens/{run_name}">',
    )
    body = body.replace(slots[1], "null")
    assert "data-src" in body and slots[0] not in body
    (docs / "_lens_body.html").write_text(
        "<!-- generated by benchmarks/site_explainer_2026_11/build_how_dyf_works_page.py --docs; edit the template, not this file -->\n"
        + body.strip()
        + "\n"
    )
    (docs / "index.qmd").write_text(
        "---\n"
        'pagetitle: "dyf: a clustering lens for embeddings"\n'
        'description-meta: "dyf fits once and then changes the level of detail freely: coarse groups, fine groups, a search index and a partition you can keep as data arrives."\n'
        "page-layout: custom\n"
        "aliases:\n  - how-it-works.html\n"
        "toc: false\n"
        "format:\n"
        "  html:\n"
        "    include-in-header: _lens_header.html\n"
        "    include-after-body: _lens_body.html\n"
        "---\n\n"
        "<!-- The homepage is generated: `python benchmarks/site_explainer_2026_11/build_how_dyf_works_page.py --docs`.\n"
        "     It replays one recorded dyf run (lens/*.json). Edit the template in that directory, not the includes. -->\n"
    )
    print(
        f"wrote docs/index.qmd, docs/_lens_header.html, docs/_lens_body.html ({len(body) / 1e3:.0f} KB), docs/lens/{run_name} "
        f"({(docs / 'lens' / run_name).stat().st_size / 1e6:.2f} MB)"
    )
